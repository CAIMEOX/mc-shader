"""Preview or remove reproducible Manifold build files and project caches."""

if __package__ in (None, ""):
    import sys
    from pathlib import Path

    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import argparse
from pathlib import Path
import shutil

from scripts.common.paths import ROOT


GENERATED = (
    "build/datapack",
    "build/resourcepack",
    "build/resourcepack-test",
    "build/launcher",
    "build/vanilla",
    "build/carrier.rgba",
    "dist-newstyle",
    "harness/build",
    "harness/.gradle",
    "harness/run",
    ".ruff_cache",
    ".pytest_cache",
)


def candidates(root):
    paths = [root / name for name in GENERATED]
    paths += sorted((root / "scripts").rglob("__pycache__"))
    return [path for path in paths if path.exists() or path.is_symlink()]


def size(path):
    if path.is_symlink() or path.is_file():
        return path.lstat().st_size
    return sum(
        p.lstat().st_size for p in path.rglob("*") if p.is_file() or p.is_symlink()
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="Remove the listed files")
    args = parser.parse_args()
    paths = candidates(ROOT)
    total = sum(size(path) for path in paths)
    for path in paths:
        if path.is_symlink() or not path.resolve().is_relative_to(ROOT):
            raise RuntimeError(f"Expected a generated path inside Manifold: {path}")
    if args.apply:
        # Native test worlds are regenerated by verification. Respect an open client.
        from scripts.run.vanilla import locked

        worlds = ROOT / "harness/build/run/clientGameTest/saves"
        if worlds.exists() and any(
            locked(world) for world in worlds.iterdir() if world.is_dir()
        ):
            raise RuntimeError("Close the Manifold test client before cleaning")
    for path in paths:
        print(
            ("Removing " if args.apply else "Would remove ")
            + str(path.relative_to(ROOT))
        )
        if args.apply:
            if path.is_dir():
                shutil.rmtree(path)
            else:
                path.unlink()
    print(f"{'Removed' if args.apply else 'Selected'} {total / (1024 * 1024):.1f} MiB")
    print(
        "Release ZIPs, build manifests, verification reports, and playable worlds are retained."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
